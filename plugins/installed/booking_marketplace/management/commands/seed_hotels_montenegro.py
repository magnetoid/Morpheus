def _stable_hash(key: str) -> int:
    """Deterministic, non-cryptographic hash used only to seed jitter/rating
    generation — never security-sensitive (hence usedforsecurity=False)."""
    return int(hashlib.md5(key.encode(), usedforsecurity=False).hexdigest(), 16)


def _jitter(lat: float, lng: float, key: str, spread: float = 0.008):
    """Deterministic tiny offset (~<=500m) so same-town pins don't stack."""
    h = _stable_hash(key)
    dlat = ((h % 1000) / 1000 - 0.5) * 2 * spread
    dlng = (((h // 1000) % 1000) / 1000 - 0.5) * 2 * spread
    return Decimal(str(round(lat + dlat, 6))), Decimal(str(round(lng + dlng, 6)))


def _rating_and_reviews(key: str, star: int):
    """Deterministic representative rating (~4.0-4.9) and review count."""
    h = _stable_hash(key)
    rating = (Decimal('4.0') + Decimal(h % 10) / Decimal('11')).quantize(Decimal('0.1'))
    review_count = 40 + (h // 10) % 460 + star * 20
    return rating, review_count


def _rate_for(star: int, ptype: str, region: str, tier_index: int) -> Decimal:
    """Representative nightly base rate, scaled by star / property type /
    region / room tier. Not the hotel's actual published rate."""
    base = Decimal(STAR_BASE.get(star, 90))
    mult = Decimal(str(PTYPE_MULT.get(ptype, 1.0))) * Decimal(str(REGION_MULT.get(region, 1.0)))
    step = TIER_STEP_HOSTEL if ptype == 'hostel' else TIER_STEP_DEFAULT
    rate = base * mult * (Decimal('1') + step * tier_index)
    return rate.quantize(Decimal('1'))


def _rooms_for(star: int, ptype: str, region: str):
    """2-4 representative RoomType specs, scaled to class."""
    if ptype in ('apartment', 'villa'):
        pool = ROOM_TIERS['apartment_villa']
    elif ptype == 'hostel':
        pool = ROOM_TIERS['hostel']
    elif ptype == 'mountain_lodge':
        pool = ROOM_TIERS['mountain_lodge']
    else:
        pool = ROOM_TIERS['default']

    n_tiers = min(2 if star <= 3 else (3 if star == 4 else 4), len(pool))
    specs = []
    for i, tier in enumerate(pool[:n_tiers]):
        room_count = max(3, tier['rooms'] - (2 if star < 4 else 0))
        specs.append(
            {
                'name': tier['name'],
                'max_occupancy': tier['max_occupancy'],
                'max_adults': tier['max_adults'],
                'max_children': tier['max_children'],
                'bed_configuration': tier['bed'],
                'size_sqm': tier['size'] + max(0, star - 3) * 3,
                'room_count': room_count,
                'amenities': tier['amenities'],
                'rate': _rate_for(star, ptype, region, i),
            }
        )
    return specs


def _base_amenities(ptype: str):
    """Amenities implied by property type alone, regardless of star/region."""
    a = ['wifi']
    if ptype != 'hostel':
        a.append('parking')
    if ptype in ('hotel', 'resort', 'boutique'):
        a.append('restaurant')
    if ptype == 'mountain_lodge':
        a += ['restaurant', 'bar', 'ev_charging']
    if ptype in ('apartment', 'villa'):
        a += ['kitchenette', 'air_conditioning', 'pet_friendly']
    if ptype == 'guesthouse':
        a += ['family_rooms', 'pet_friendly']
    return a


def _star_amenities(star: int, ptype: str):
    """Amenities implied by star class (higher star -> more facilities)."""
    a = []
    if ptype in ('hotel', 'resort', 'boutique') and star >= 3:
        a.append('bar')
    if star >= 4 and ptype not in ('hostel', 'guesthouse'):
        a += ['air_conditioning', 'pool']
    if star >= 4 and ptype in ('resort', 'boutique', 'hotel'):
        a.append('gym')
    if star >= 4 and ptype in ('resort', 'boutique'):
        a.append('spa')
    if star == 5:
        a += ['concierge', 'room_service']
        if ptype == 'resort':
            a.append('airport_shuttle')
    return a


def _region_amenities(star: int, ptype: str, region: str):
    """Amenities implied by being on the coast (sea view / beachfront)."""
    a = []
    if (
        region in COASTAL_REGIONS
        and star >= 3
        and ptype in ('hotel', 'resort', 'boutique', 'villa')
    ):
        a.append('sea_view')
    if region in COASTAL_REGIONS and ptype == 'resort':
        a.append('beachfront')
    return a


def _amenities_for(star: int, ptype: str, region: str):
    """Representative hotel-level amenity slugs, fitting the class."""
    combined = (
        _base_amenities(ptype)
        + _star_amenities(star, ptype)
        + _region_amenities(star, ptype, region)
    )
    out = []
    for x in combined:
        if x not in out:
            out.append(x)
    return out


