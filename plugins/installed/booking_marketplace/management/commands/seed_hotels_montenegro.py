_TIER_WORD = {2: 'a simple, comfortable', 3: 'a well-appointed', 4: 'an upscale', 5: 'a luxury'}

# Guest-salient amenities, most distinguishing first, as noun phrases for the
# meta description. Only amenities the hotel actually has are ever named: a
# description is a public claim, like the rating this store already stopped
# inventing (the aggregateRating landmine) — it must not promise a spa.
_FEATURE_PHRASES = [
    ('sea_view', 'sea views'),
    ('beachfront', 'a beachfront'),
    ('spa', 'a spa'),
    ('pool', 'a pool'),
    ('restaurant', 'a restaurant'),
    ('gym', 'a gym'),
    ('airport_shuttle', 'an airport shuttle'),
    ('wifi', 'free WiFi'),
    ('parking', 'parking'),
]


def _feature_phrase(amenities) -> str:
    """Up to three of the hotel's real, guest-salient amenities, as a phrase
    ('sea views, a spa and a pool'). Empty when it has none worth naming."""
    have = set(amenities or ())
    picked = [phrase for slug, phrase in _FEATURE_PHRASES if slug in have][:3]
    if not picked:
        return ''
    if len(picked) == 1:
        return picked[0]
    return ', '.join(picked[:-1]) + ' and ' + picked[-1]


def _legacy_short_blurb(town: str, star: int, ptype_label: str) -> str:
    """The pre-v0.73.3 short_description — tier + type + town only, which
    collided across every same-class hotel in a town (18 groups / 52 hotels
    live). Kept so `refresh_hotel_blurbs` can tell a platform-generated blurb
    from one a host has since edited, and rewrite only the former — the
    SeoMeta.auto_filled rule (never clobber a human's words)."""
    return f'{_TIER_WORD[star].capitalize()} {ptype_label.lower()} in {town}.'


def _blurb_for(name: str, town: str, star: int, ptype_label: str, amenities):
    """(short_description, description) for one hotel.

    short_description is the hotel page's meta description (stay_views:
    `seo_description`). Leading with the unique hotel name makes all 100
    distinct, and naming real amenities gives each an in-range (70-160 char)
    summary in place of 'An upscale hotel in Podgorica.' on nine hotels at once.
    `description` is the on-page prose and is unchanged."""
    tier_word = _TIER_WORD[star]
    ptype_lower = ptype_label.lower()
    lead = f'{name} is {tier_word} {star}-star {ptype_lower} in {town}, Montenegro'
    feature = _feature_phrase(amenities)
    short = f'{lead}, with {feature}.' if feature else f'{lead}.'
    description = (
        f'{name} is {tier_word} {star}-star {ptype_lower} in {town}, Montenegro, offering '
        f'comfortable rooms for couples, families and small groups, with a range of room types '
        f'to choose from.'
    )
    return short, description


def _field_values(name: str, town: str, star: int, ptype: str) -> dict:
    """Compute every derived Property field for one hotel (pure function)."""
    lat_base, lng_base, region = TOWN_COORDS[town]
    slug = slugify(name)
    lat, lng = _jitter(lat_base, lng_base, slug)
    rating, review_count = _rating_and_reviews(slug, star)
    ptype_label = PTYPE_LABELS.get(ptype, 'Hotel')
    amenities = _amenities_for(star, ptype, region)
    short_desc, desc = _blurb_for(name, town, star, ptype_label, amenities)
    return {
        'slug': slug,
        'name': name,
        'property_type': ptype,
        'star_rating': star,
        'short_description': short_desc,
        'description': desc,
        'region': region,
        'location': town,
        'address': f'{town}, Montenegro',
        'latitude': lat,
        'longitude': lng,
        'amenities': amenities,
        'check_in_time': time(15, 0) if star == 5 else time(14, 0),
        'check_out_time': time(11, 0),
        'policies': _policies_for(star),
        'rating': rating,
        'review_count': review_count,
        'is_featured': name in FEATURED_NAMES,
        'is_active': True,
    }


def _backfill_property(prop, values: dict) -> None:
    """Fill fields still empty on a pre-existing row — never clobber
    something an admin/host may have already edited."""
    is_empty = {
        'short_description': not prop.short_description,
        'description': not prop.description,
        'location': not prop.location,
        'address': not prop.address,
        'latitude': prop.latitude is None,
        'longitude': prop.longitude is None,
        'amenities': not prop.amenities,
        'check_in_time': not prop.check_in_time,
        'check_out_time': not prop.check_out_time,
        'policies': not prop.policies,
        'rating': not prop.rating,
        'review_count': not prop.review_count,
    }
    dirty = [field for field, empty in is_empty.items() if empty]
    for field in dirty:
        setattr(prop, field, values[field])
    if dirty:
        prop.save(update_fields=dirty)


def _create_room_types(prop, star: int, ptype: str, region: str, room_type_model) -> int:
    """Create the class-driven RoomTypes for a brand-new property. No-op if
    the property already has any (never re-seeds/edits existing rooms)."""
    if prop.room_types.exists():
        return 0
    for i, spec in enumerate(_rooms_for(star, ptype, region)):
        room_type_model.objects.create(
            property=prop,
            name=spec['name'],
            slug=slugify(spec['name']),
            max_occupancy=spec['max_occupancy'],
            max_adults=spec['max_adults'],
            max_children=spec['max_children'],
            bed_configuration=spec['bed_configuration'],
            size_sqm=spec['size_sqm'],
            base_rate=Money(spec['rate'], 'EUR'),
            room_count=spec['room_count'],
            amenities=spec['amenities'],
            is_active=True,
            sort_order=i,
        )
    return len(prop.room_types.all())


class Command(BaseCommand):
    help = 'Seed ~100 real Montenegro hotels (representative rooms/rates/amenities). Idempotent.'

    def handle(self, *args, **opts):
        from plugins.installed.booking_marketplace.models import Property, RoomType
        from plugins.installed.catalog.models import Vendor

        hotels_created = hotels_existing = rooms_created = 0

        for name, town, star, ptype in HOTELS:
            values = _field_values(name, town, star, ptype)

            vendor, _ = Vendor.objects.get_or_create(
                slug=values['slug'],
                defaults={
                    'name': name,
                    'description': values['short_description'],
                    'is_active': True,
                },
            )

            defaults = {k: v for k, v in values.items() if k != 'slug'}
            defaults['vendor'] = vendor
            prop, was_created = Property.objects.get_or_create(
                slug=values['slug'], defaults=defaults
            )

            _backfill_property(prop, values)
            rooms_created += _create_room_types(prop, star, ptype, values['region'], RoomType)
            prop.recalc_price_from(save=True)

            hotels_created += was_created
            hotels_existing += not was_created

        self.stdout.write(
            self.style.SUCCESS(
                f'Hotels seeded: {hotels_created} created, {hotels_existing} already present '
                f'({Property.objects.count()} total). Rooms created this run: {rooms_created} '
                f'({RoomType.objects.count()} total).'
            )
        )
