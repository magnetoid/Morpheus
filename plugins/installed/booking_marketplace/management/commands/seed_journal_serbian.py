class Command(BaseCommand):
    help = 'Publish recovered Serbian journal article(s). Idempotent.'

    def handle(self, *args, **options):
        from plugins.installed.cms.models import Page

        now = timezone.now()
        page, created = Page.objects.get_or_create(
            slug='manastiri-crne-gore-vodic',
            defaults={
                'title': 'Манастири Црне Горе: водич кроз духовно благо',
                'excerpt': (
                    'Од Острога уклесаног у стену до Мораче и Пиве — водич кроз преко 150 '
                    'манастира Црне Горе, са итинераром и саветима за посету.'
                )[:300],
                'body': _MANASTIRI_BODY,
                'state': 'published',
                'publish_at': now - timedelta(days=2),
                'metadata': {
                    'category': 'journal',
                    'language': 'sr',
                    'author': 'Марко Милосављевић',
                },
            },
        )
        if not created:
            dirty = []
            if page.state != 'published':
                page.state = 'published'
                dirty.append('state')
            if not page.body:
                page.body = _MANASTIRI_BODY
                dirty.append('body')
            # Fully seed-owned article — keep all metadata canonical (this also
            # migrates the earlier placeholder byline to the real author).
            want = {'category': 'journal', 'language': 'sr', 'author': 'Марко Милосављевић'}
            md = dict(page.metadata or {})
            if any(md.get(k) != v for k, v in want.items()):
                md.update(want)
                page.metadata = md
                dirty.append('metadata')
            if dirty:
                page.save(update_fields=dirty)
        self.stdout.write(
            self.style.SUCCESS(f'Serbian journal: {"created" if created else "ensured"} 1 article.')
        )
